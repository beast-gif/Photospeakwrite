def get_glyph(ch: str):
    """Return glyph dict for a character; uppercase fallback; '?' if unknown."""
    if ch in HERSHEY_SIMPLEX:
        return HERSHEY_SIMPLEX[ch]
    up = ch.upper()
    if up in HERSHEY_SIMPLEX:
        return HERSHEY_SIMPLEX[up]
    # unknown -> render a space
    return HERSHEY_SIMPLEX[" "]


